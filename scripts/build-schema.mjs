// Generate the two schema artefacts from their sources.
//
//  1. src/madmp-schema.js, the vendored RDA DMP Common Standard v1.2 schema as an ES module, so
//     the page validates a plan without a request and without a JSON import (which needs an
//     import attribute older browsers reject). The vendored JSON in schema/ is the source and
//     stays byte-identical to the published standard; tests/schema.test.mjs pins its hash.
//  2. schema/dmp.schema.json, the schema of this tool's extension (`dmp.actionable_dmp`) on top
//     of maDMP, generated from src/requirements.js so it cannot drift from the catalogue.
//
// tests/schema.test.mjs fails when either committed file differs from what this script makes.
//
//   node scripts/build-schema.mjs          write both
//   node scripts/build-schema.mjs --check  exit 1 if either is stale

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { GUIDE, MADMP, QUESTIONS } from '../src/requirements.js';
import { EXTENSION, SCHEMA_ID, SCHEMA_VERSION } from '../src/plan.js';

const at = (rel) => fileURLToPath(new URL(`../${rel}`, import.meta.url));

export function moduleText() {
  const schema = JSON.parse(readFileSync(at(MADMP.schemaFile), 'utf8'));
  return [
    `// GENERATED by scripts/build-schema.mjs from ${MADMP.schemaFile}. Do not edit.`,
    `// RDA DMP Common Standard for machine-actionable DMPs, v${MADMP.version}, ${MADMP.repository}`,
    '// (released into the public domain under the Unlicense by its authors).',
    `export const MADMP_SCHEMA = ${JSON.stringify(schema)};`,
    '',
  ].join('\n');
}

export function buildSchema() {
  return {
    $schema: 'https://json-schema.org/draft/2020-12/schema',
    $id: SCHEMA_ID,
    title: 'Actionable DMP',
    description:
      `dmp.json, extension schema version ${SCHEMA_VERSION}: a machine-actionable DMP after the RDA DMP Common Standard ` +
      `v${MADMP.version} (maDMP-schema-${MADMP.version}.json, next to this file), plus the answers to the fifteen questions of ` +
      `Science Europe's ${GUIDE.title} (https://doi.org/${GUIDE.versionDoi}) in dmp.${EXTENSION}. ` +
      'Generated from src/requirements.js; do not edit by hand. CC BY 4.0.',
    allOf: [{ $ref: `maDMP-schema-${MADMP.version}.json` }],
    type: 'object',
    properties: {
      $schema: { type: 'string' },
      dmp: {
        type: 'object',
        properties: {
          [EXTENSION]: {
            type: 'object',
            description: 'Added by Actionable DMP. Everything a machine can act on stays in the standard maDMP fields.',
            required: ['schema_version', 'answers'],
            additionalProperties: false,
            properties: {
              schema_version: { type: 'string', const: SCHEMA_VERSION },
              guide: {
                type: 'object',
                properties: { title: { type: 'string' }, doi: { type: 'string' } },
              },
              answers: {
                type: 'object',
                additionalProperties: false,
                properties: Object.fromEntries(QUESTIONS.map((q) => [q.id, {
                  type: 'string',
                  description: `Science Europe core requirement ${q.section}, question ${q.id}.`,
                }])),
              },
              versions: {
                type: 'array',
                description: 'The saved versions of the plan, numbered from 1 in increasing order.',
                items: {
                  type: 'object',
                  required: ['version', 'date'],
                  additionalProperties: false,
                  properties: {
                    version: { type: 'integer', minimum: 1 },
                    date: { type: 'string', format: 'date-time' },
                    note: { type: 'string', description: 'What changed, or why this version was saved.' },
                  },
                },
              },
            },
          },
        },
      },
    },
  };
}

export const schemaText = () => `${JSON.stringify(buildSchema(), null, 2)}\n`;

const OUTPUTS = [['src/madmp-schema.js', moduleText], ['schema/dmp.schema.json', schemaText]];

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    const stale = OUTPUTS.filter(([rel, make]) => readFileSync(at(rel), 'utf8') !== make()).map(([rel]) => rel);
    if (stale.length) { console.error(`stale: ${stale.join(', ')}`); process.exit(1); }
  } else {
    for (const [rel, make] of OUTPUTS) writeFileSync(at(rel), make());
    console.log(OUTPUTS.map(([rel]) => rel).join(' and '), 'written');
  }
}
